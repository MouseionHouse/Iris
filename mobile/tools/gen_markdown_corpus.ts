// Runs Cinny's own markdown plugin over a corpus and writes CinnyMarkdownCorpusTest.kt, so the Kotlin
// port is held to the web client's exact output. Run from mobile/: ~/.bun/bin/bun tools/gen_markdown_corpus.ts
import { writeFileSync } from 'fs';
import {
  parseBlockMD,
  parseInlineMD,
  unescapeMarkdownBlockSequences,
  unescapeMarkdownInlineSequences,
  escapeMarkdownInlineSequences,
} from '../../src/app/plugins/markdown';
import { findAndReplace } from '../../src/app/utils/findAndReplace';

// Copied from src/app/components/editor/output.ts (which imports slate).
const HTML_TAG_REG_G = /<([\w-]+)(?: [^>]*)?(?:(?:\/>)|(?:>.*?<\/\1>))/g;
const ignoreHTMLParseInlineMD = (text: string): string =>
  findAndReplace(
    text,
    HTML_TAG_REG_G,
    (m) => m[0],
    (t) => parseInlineMD(t)
  ).join('');

const corpus: string[] = [
  'just plain text',
  'line one\nline two',
  'spike **b** and _i_ and *s* check',
  'use snake_case_name here',
  'run `foo` now',
  '__under__ and ~~strike~~ and ||spoiler||',
  '***both***',
  '**bold *italic* inside**',
  '*a* *b*',
  'a * b * c',
  '\\*not italic\\*',
  'see [here](https://example.org) ok',
  '[x](ftp://nope)',
  'https://example.org/a_b_c_d and _it_',
  'https://example.org/**x** and **y**',
  'mailto://a*b*c then *d*',
  '`code with **stars**` and **bold**',
  '``',
  '# Title',
  '###### six',
  '####### seven',
  '#no space',
  '> hi',
  '> quote *it*\n>second\nafter',
  '>\n> x',
  '- a\n- b',
  '* a\n* b',
  '1. one\n2. two',
  'a. alpha\nb. beta',
  'i. roman\nI. upper',
  '- a\n  - nested\n- b',
  '- a\n* mixed',
  '* a\n  1. inner\n* b',
  '- a\n    - deep\n- back',
  '```\nx < y\nz\n```',
  '```kotlin\nfun main() {}\n```',
  '```example.json\n{"a": 1}\n```',
  '````\n```\ninner\n````',
  '```\nunclosed',
  'text\n```\ncode\n```\nafter',
  '\\# not heading',
  '\\> not quote',
  '\\- not list',
  '\\\\# double',
  'mix # hash **b**\n\n\nblank lines',
  '&lt;b&gt; escaped &amp; **b**',
  'x <a href="https://matrix.to/#/@a:b">@a_b_c</a> *y*',
  'x <a href="https://matrix.to/#/@a:b">@a</a> and <a href="https://matrix.to/#/@c:d">@c</a> _z_',
  '<img data-mx-emoticon src="mxc://a/b" alt=":x_y:" title=":x_y:" height="32" /> _i_',
  '||spoil **bold**||',
  '~~a~~~',
  '**a** **b**',
  '1) not list',
  'emoji 👍 **b** ü',
  '',
];

const q = (s: string) => JSON.stringify(s).replace(/\$/g, '\\$');
const rows = corpus.map((input) => {
  const block = parseBlockMD(input, ignoreHTMLParseInlineMD);
  const inline = parseInlineMD(input);
  const plain = unescapeMarkdownBlockSequences(input, unescapeMarkdownInlineSequences);
  const esc = escapeMarkdownInlineSequences(input);
  return `        Case(${q(input)}, ${q(block)}, ${q(inline)}, ${q(plain)}, ${q(esc)}),`;
});

writeFileSync(
  'shared/src/commonTest/kotlin/house/mouseion/iris/ui/CinnyMarkdownCorpusTest.kt',
  `package house.mouseion.iris.ui

import kotlin.test.Test
import kotlin.test.assertEquals

/** Generated by tools/gen_markdown_corpus.ts from Cinny's own markdown plugin; do not edit by hand. */
class CinnyMarkdownCorpusTest {
    private class Case(val input: String, val block: String, val inline: String, val plain: String, val escaped: String)

    private val cases = listOf(
${rows.join('\n')}
    )

    @Test
    fun blockMarkdownMatchesCinny() = cases.forEach { assertEquals(it.block, parseBlockMD(it.input, ::ignoreHtmlParseInlineMD), "block: \${it.input}") }

    @Test
    fun inlineMarkdownMatchesCinny() = cases.forEach { assertEquals(it.inline, parseInlineMD(it.input), "inline: \${it.input}") }

    @Test
    fun unescapingMatchesCinny() = cases.forEach {
        assertEquals(it.plain, unescapeMarkdownBlockSequences(it.input, ::unescapeMarkdownInlineSequences), "plain: \${it.input}")
    }

    @Test
    fun escapingMatchesCinny() = cases.forEach { assertEquals(it.escaped, escapeMarkdownInlineSequences(it.input), "escape: \${it.input}") }
}
`
);
console.log(`wrote ${rows.length} cases`);
