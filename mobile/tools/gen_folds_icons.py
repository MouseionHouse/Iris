#!/usr/bin/env python3
"""Generates FoldsIcons.kt from the published folds package's `Icons` (dist/index.js).

Usage: gen_folds_icons.py <folds package dir> <output .kt>
Cinny draws every icon with folds; these are the same 24x24 paths as Compose ImageVectors.
"""
import math
import re
import sys

src_dir, out_path = sys.argv[1], sys.argv[2]
js = open(f"{src_dir}/dist/index.js").read()
version = re.search(r'"version":\s*"([^"]+)"', open(f"{src_dir}/package.json").read()).group(1)
start = js.find("const Icons = {")
end = js.find("\n};", start)
block = js[start:end]


def fmt(v):
    s = f"{v:.4f}".rstrip("0").rstrip(".")
    return "0" if s == "-0" else s


def to_path(tag, a):
    if tag == "path":
        return a["d"], a.get("fillRule") == "evenodd"
    if tag == "circle":
        cx, cy, r = float(a["cx"]), float(a["cy"]), float(a["r"])
        return (f"M{fmt(cx - r)} {fmt(cy)}A{fmt(r)} {fmt(r)} 0 1 0 {fmt(cx + r)} {fmt(cy)}"
                f"A{fmt(r)} {fmt(r)} 0 1 0 {fmt(cx - r)} {fmt(cy)}Z"), False
    x, y, w, h = (float(a[k]) for k in ("x", "y", "width", "height"))
    corners = [(x, y), (x + w, y), (x + w, y + h), (x, y + h)]
    t = a.get("transform")
    if t:
        ang, ox, oy = (float(v) for v in re.match(r"rotate\(([-\d.]+) ([-\d.]+) ([-\d.]+)\)", t).groups())
        rad = math.radians(ang)
        cos, sin = math.cos(rad), math.sin(rad)
        corners = [(ox + (px - ox) * cos - (py - oy) * sin, oy + (px - ox) * sin + (py - oy) * cos) for px, py in corners]
    d = "M" + "L".join(f"{fmt(px)} {fmt(py)}" for px, py in corners) + "Z"
    return d, False


# Evaluate folds' own `Icons` with stub jsx functions: some icons choose filled/outline deep inside
# their children, which only running the code resolves.
import json
import subprocess

node_script = """
const Fragment = 'Fragment';
const flat = (c) => (Array.isArray(c) ? c.flat(Infinity) : [c]).filter((x) => x && typeof x === 'object');
const jsx = (tag, props) => ({ tag, props, children: flat(props && props.children) });
const jsxs = jsx;
""" + block + """
};
const out = {};
for (const [name, fn] of Object.entries(Icons)) {
  const walk = (node) => node.tag === 'Fragment' ? node.children.flatMap(walk) : [{ tag: node.tag, attrs: node.props }];
  out[name] = { outline: walk(fn(false)), filled: fn.length > 0 ? walk(fn(true)) : null };
}
console.log(JSON.stringify(out));
"""
icons = json.loads(subprocess.run(["node", "-e", node_script], capture_output=True, text=True, check=True).stdout)

entries = []
for name, forms in icons.items():
    outline = [to_path(e["tag"], {k: str(v) for k, v in e["attrs"].items()}) for e in forms["outline"]]
    entries.append((name, outline))
    if forms["filled"] is not None:
        filled = [to_path(e["tag"], {k: str(v) for k, v in e["attrs"].items()}) for e in forms["filled"]]
        if filled != outline:
            entries.append((name + "Filled", filled))

lines = [
    "package house.mouseion.chat.ui.theme",
    "",
    "import androidx.compose.ui.graphics.Color",
    "import androidx.compose.ui.graphics.PathFillType",
    "import androidx.compose.ui.graphics.SolidColor",
    "import androidx.compose.ui.graphics.vector.ImageVector",
    "import androidx.compose.ui.graphics.vector.addPathNodes",
    "import androidx.compose.ui.unit.dp",
    "",
    f"// Generated by mobile/tools/gen_folds_icons.py from folds {version} (dist/index.js `Icons`). Do not edit.",
    "",
    "private fun foldsIcon(name: String, vararg paths: Pair<String, Boolean>): ImageVector =",
    "    ImageVector.Builder(name, 24.dp, 24.dp, 24f, 24f).apply {",
    "        for ((d, evenOdd) in paths) {",
    "            addPath(addPathNodes(d), fill = SolidColor(Color.Black), pathFillType = if (evenOdd) PathFillType.EvenOdd else PathFillType.NonZero)",
    "        }",
    "    }.build()",
    "",
    "/** Cinny's icons: folds `Icons`, outline by default and `…Filled` where folds has a filled form. */",
    "object FoldsIcons {",
]
for name, paths in entries:
    args = ", ".join(f'"{d}" to {"true" if eo else "false"}' for d, eo in paths)
    lines.append(f'    val {name}: ImageVector by lazy {{ foldsIcon("{name}", {args}) }}')
lines.append("}")
open(out_path, "w").write("\n".join(lines) + "\n")
print(f"{len(entries)} icons")
